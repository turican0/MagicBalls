#!/usr/bin/env python3
"""
Generuje atribuce 3D modelů ze Sketchfabu pro MagicBalls.

Vstup:
  godot-code/entites/sources/licence.txt        (seznam odkazů, vč. kategorií "orbs:" apod.)
  godot-code/assets/*/Readme.html               (jeden odkaz na model)
  godot-code/entites/sources/modified_models.txt  (VOLITELNÉ: upravené modely)

  godot-code/credits/other_credits.json         (ručně: tým, knihovny, poděkování bez známé licence)

Výstup:
  CREDITS.md                       (celý se přegeneruje)
  godot-code/credits/models_credits.json   (pro obrazovku Credits ve hře, klávesa C)

Použití (z kořene repa, potřebuje internet, jen stdlib):
  python tools/sketchfab_credits.py            # stáhne autory a licence z API
  python tools/sketchfab_credits.py --offline  # jen tabulka z odkazů, bez autorů
  python tools/sketchfab_credits.py --from-json  # bez internetu, z minule stažených dat

Modely bez známé licence (smazané/skryté) jdou do poděkování.

modified_models.txt: jeden model na řádek, "UID_nebo_část_URL | poznámka o úpravě", např.
  d37f9bc2247942b9bc9bf5aa7b3080e9 | zredukován počet trojúhelníků, nové materiály
"""
import argparse, json, re, sys, time, urllib.request, urllib.error
from pathlib import Path

ROOT = Path.cwd()
LICENCE_TXT = ROOT / "godot-code/entites/sources/licence.txt"
MODIFIED_TXT = ROOT / "godot-code/entites/sources/modified_models.txt"
ASSET_READMES = {
    "castle": "Environment", "cat": "Environment", "ballon": "Environment",
    "carpets": "Environment", "vase": "Environment",
}
CREDITS_MD = ROOT / "CREDITS.md"
OUT_JSON = ROOT / "godot-code/credits/models_credits.json"
OTHER_JSON = ROOT / "godot-code/credits/other_credits.json"
HEADER = """# Credits & Licenses

**MagicBalls** is a fan remake of *Magic Carpet 2: The Netherworlds* built with the [Godot Engine](https://godotengine.org/) and the [REMC2](https://github.com/turican0/remc2) engine. The game code is licensed under GPL-3.0 (see `LICENSE`). The original game data (Bullfrog / Electronic Arts) is **not** included – you must own the game (e.g. the GOG version).

Thank you to everyone whose work made this project possible! In the game the credits are shown with the **C** key on the start screen.

<!-- Generated by tools/sketchfab_credits.py from godot-code/credits/*.json - edit those, not this file. -->
"""
URL_RE = re.compile(r"https://sketchfab\.com/3d-models/([a-z0-9\-]*?)-?([0-9a-f]{32})")
OK_SLUGS = {"by", "by-sa", "cc0"}          # použitelné i komerčně (s atribucí u by*)
RISKY = {"by-nc", "by-nc-sa", "by-nc-nd", "by-nd", "st", "unavailable"}


def collect():
    """Vrátí dict uid -> {slug, url, category} (bez duplicit, zachová pořadí)."""
    items, category = {}, "General (unsorted)"
    if LICENCE_TXT.exists():
        for raw in LICENCE_TXT.read_text(encoding="utf-8", errors="replace").splitlines():
            line = raw.strip()
            if not line:
                continue
            m = URL_RE.search(line)
            if m:
                slug, uid = m.groups()
                items.setdefault(uid, {"slug": slug, "url": f"https://sketchfab.com/3d-models/{slug}-{uid}",
                                       "category": category})
            elif line.endswith(":") or (not line.startswith("http") and ":" not in line):
                category = line.rstrip(":").strip().title()
    for folder, cat in ASSET_READMES.items():
        p = ROOT / "godot-code/assets" / folder / "Readme.html"
        if p.exists():
            m = URL_RE.search(p.read_text(encoding="utf-8", errors="replace"))
            if m:
                slug, uid = m.groups()
                items.setdefault(uid, {"slug": slug, "url": f"https://sketchfab.com/3d-models/{slug}-{uid}",
                                       "category": cat})
    return items


def load_modified():
    mods = {}
    if MODIFIED_TXT.exists():
        for raw in MODIFIED_TXT.read_text(encoding="utf-8").splitlines():
            if not raw.strip() or raw.lstrip().startswith("#"):
                continue
            key, _, note = raw.partition("|")
            mods[key.strip()] = note.strip() or "upraveno"
    return mods


def is_modified(uid, slug, mods):
    for k, note in mods.items():
        if k and (k == uid or k in slug):
            return note
    return ""


def fetch(uid, retries=3):
    req = urllib.request.Request(f"https://api.sketchfab.com/v3/models/{uid}",
                                 headers={"User-Agent": "MagicBalls-credits/1.0"})
    for i in range(retries):
        try:
            with urllib.request.urlopen(req, timeout=20) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code in (404, 403, 410):
                return {"_error": f"HTTP {e.code} (model smazán nebo skrytý)"}
            time.sleep(2 * (i + 1))
        except Exception:  # síť
            time.sleep(2 * (i + 1))
    return {"_error": "nelze načíst (zkus znovu)"}


def parse(data, fallback_slug):
    """Z odpovědi API vytáhne title/author/licenci."""
    if "_error" in data:
        return {"title": fallback_slug.replace("-", " ").title(), "author": "", "author_url": "",
                "license": data["_error"], "license_url": "", "slug": "unavailable", "ok": False}
    user, lic = data.get("user") or {}, data.get("license") or {}
    slug = (lic.get("slug") or "").lower()
    return {
        "title": data.get("name") or fallback_slug.replace("-", " ").title(),
        "author": user.get("displayName") or user.get("username") or "",
        "author_url": user.get("profileUrl") or (f"https://sketchfab.com/{user['username']}" if user.get("username") else ""),
        "license": lic.get("fullName") or lic.get("label") or "neznámá",
        "license_url": lic.get("url") or "",
        "slug": slug,
        "ok": slug in OK_SLUGS,
    }


def md_escape(s):
    return s.replace("|", "\\|").replace("\n", " ").strip()


def md_link(text, url):
    return f"[{md_escape(text)}]({url})" if url else md_escape(text)


def build_markdown(rows, other, offline):
    out = [HEADER, "## MagicBalls team", ""]
    for t in other.get("team", []):
        role = f" – {md_escape(t['role'])}" if t.get("role") else ""
        out.append(f"- **{md_link(t['name'], t.get('url'))}**{role}")
    out += ["", "## 3D models (Sketchfab)", "",
            "The models below were downloaded from [Sketchfab](https://sketchfab.com/) and are used under the licenses "
            "stated by their authors. They were converted to Godot formats, and some of them were further modified "
            "(the **Modified** column marks them). If you are an author and want your credit changed or a model "
            "removed, please open an issue.", ""]
    if offline:
        out += ["> ⚠️ Autoři a licence zatím nejsou doplněni. Spusť `python tools/sketchfab_credits.py`.", ""]
    known = [r for r in rows if offline or r.get("slug") != "unavailable"]
    unknown = [r for r in rows if not offline and r.get("slug") == "unavailable"]
    cats = {}
    for r in known:
        cats.setdefault(r["category"], []).append(r)
    for cat, lst in cats.items():
        out += [f"### {cat}", "", "| Model | Author | License | Modified |", "|---|---|---|---|"]
        for r in lst:
            title = f"[{md_escape(r['title'])}]({r['url']})"
            author = (f"[{md_escape(r['author'])}]({r['author_url']})" if r["author"] and r["author_url"]
                      else md_escape(r["author"]) or "—")
            lic = (f"[{md_escape(r['license'])}]({r['license_url']})" if r["license_url"] else md_escape(r["license"]) or "—")
            if r.get("slug") in RISKY:
                lic += " ⚠️"
            out.append(f"| {title} | {author} | {lic} | {md_escape(r['modified']) or '—'} |")
        out.append("")
    bad = [r for r in known if r.get("slug") in RISKY or (not offline and not r["ok"] and r.get("slug") != "")]
    if bad:
        out += ["#### ⚠️ Licenses to check (NonCommercial / NoDerivs / Standard)", ""]
        out += [f"- {md_escape(r['title'])} – {md_escape(r['license'])} – {r['url']}" for r in bad]
        out.append("")
    out += ["## Other assets, code and libraries", "", "| Component | Author | License |", "|---|---|---|"]
    for c in other.get("components", []):
        out.append(f"| {md_link(c['title'], c.get('url'))} | {md_escape(c.get('author', '')) or '—'} "
                   f"| {md_link(c['license'], c.get('license_url'))} |")
    out += ["", "## Special thanks", "", "Also thanks to these works and people (the license is not known):", ""]
    for t in other.get("thanks", []):
        by = f" – {md_escape(t['author'])}" if t.get("author") else ""
        out.append(f"- {md_link(t['title'], t.get('url'))}{by}")
    for r in unknown:
        out.append(f"- {md_link(r['title'], r['url'])} (Sketchfab, model no longer available)")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--from-json", action="store_true", help="autoři a licence z minulého models_credits.json")
    a = ap.parse_args()
    items, mods = collect(), load_modified()
    if not items:
        sys.exit("Nenalezeny žádné odkazy – spouštěj z kořene repozitáře.")
    cached = {}
    if a.from_json:
        cached = {r["uid"]: r for r in json.loads(OUT_JSON.read_text(encoding="utf-8"))}
    rows = []
    for n, (uid, it) in enumerate(items.items(), 1):
        if uid in cached:
            info = {k: cached[uid][k] for k in ("title", "author", "author_url", "license", "license_url", "slug", "ok")}
        elif a.offline:
            info = {"title": it["slug"].replace("-", " ").title(), "author": "", "author_url": "",
                    "license": "", "license_url": "", "slug": "", "ok": False}
        else:
            print(f"[{n}/{len(items)}] {it['slug']}", file=sys.stderr)
            info = parse(fetch(uid), it["slug"])
            time.sleep(0.3)
        rows.append({**info, "uid": uid, "url": it["url"], "category": it["category"],
                     "modified": is_modified(uid, it["slug"], mods)})
    other = json.loads(OTHER_JSON.read_text(encoding="utf-8")) if OTHER_JSON.exists() else {}
    CREDITS_MD.write_text(build_markdown(rows, other, a.offline), encoding="utf-8")
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(rows, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"Hotovo: {len(rows)} modelů -> {CREDITS_MD}, {OUT_JSON}", file=sys.stderr)


if __name__ == "__main__":
    main()
